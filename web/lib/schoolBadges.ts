export type SchoolBadge = { abbr: string; bg: string; fg: string; known: boolean };

/** Badge for a school display name. Unknown → neutral with initials. */
export function schoolBadge(school: string): SchoolBadge {
  const hit = B[school];
  if (hit) return { abbr: hit[0], bg: hit[1], fg: hit[2], known: true };
  const words = school.replace(/[^A-Za-z\s-]/g, "").split(/[\s-]+/).filter(w => w && !/^(of|the|and)$/i.test(w));
  const abbr = (words.length > 1 ? words.map(w => w[0]).join("") : (words[0] ?? "?").slice(0, 4)).slice(0, 4).toUpperCase();
  return { abbr, bg: "var(--bc-raised)", fg: "var(--bc-text)", known: false };
}
